private func error(_ a: SIMD3<Double>, _ b: SIMD3<Double>) -> Double {
    let d = a-b
    return max(abs(d.x), abs(d.y), abs(d.z))
}

@Test func lorenzDerivativeAndEquilibria() {
    let m = LorenzParameters()
    #expect(error(LorenzMath.derivative(SIMD3(1,1,1), parameters: m), SIMD3(0,26,-5/3)) < 1e-12)
    #expect(LorenzMath.derivative(.zero, parameters: m) == .zero)
    let x = sqrt(m.beta * (m.rho-1))
    #expect(error(LorenzMath.derivative(SIMD3(x,x,m.rho-1), parameters: m), .zero) < 1e-12)
}

@Test func rk4MatchesIndependentDOP853AndConverges() {
    // Generated by scripts/lorenz-reference.py (SciPy 1.18.1, rtol=atol=1e-13).
    let reference = SIMD3(-9.378570010925381, -8.357033788427005, 29.36232533736376)
    func integrate(_ count: Int, end: Double = 1) -> SIMD3<Double> {
        var p = SIMD3<Double>(1,1,1)
        for _ in 0..<count { p = LorenzMath.rk4(p, parameters: LorenzParameters(), dt: end / Double(count)) }
        return p
    }
    #expect(error(integrate(240), reference) < 0.000002)
    // At t=0.5 the nominal dt and half-dt errors are in the fourth-order regime.
    // At t=1 component cancellation makes a two-resolution ratio misleading.
    let halfSecond = SIMD3(1.1982729680495101, -8.867197729736843, 32.45474021150348)
    let coarse = error(integrate(120, end: 0.5), halfSecond)
    let fine = error(integrate(240, end: 0.5), halfSecond)
    #expect(coarse / fine > 14 && coarse / fine < 20)
}

@Test func seededResetAndBatchingAreRepeatable() throws {
    var a = LorenzReference(), b = LorenzReference()
    try a.advance(steps: 2400, parameters: LorenzParameters())
    for _ in 0..<100 { try b.advance(steps: 24, parameters: LorenzParameters()) }
    #expect(a.point == b.point)
    let expected = a.point
    a.reset()
    #expect(a.steps == 0)
    try a.advance(steps: 2400, parameters: LorenzParameters())
    #expect(a.point == expected)
    #expect(LorenzMath.initialPoint(index: 0, seed: 1) != LorenzMath.initialPoint(index: 1, seed: 1))
    #expect(LorenzMath.initialPoint(index: 0, seed: 1) != LorenzMath.initialPoint(index: 0, seed: 2))
}

@Test func clockIsRefreshIndependentAndPauseDoesNotAccumulate() {
    for hz in [30,60,120,144] {
        var clock = FixedStepClock()
        var count = 0
        for _ in 0..<(hz*10) { count += clock.consume(elapsed: 1/Double(hz)) }
        #expect(count == 2400)
        #expect(clock.consume(elapsed: 300, paused: true) == 0)
        #expect(clock.consume(elapsed: 1/240) == 1)
        clock.reset()
        #expect(clock.steps == 0 && clock.remainder == 0)
    }
}

