@Test func stableDynamicsConvergeWithoutRecoveryOrForcedMotion() throws {
    // rho < 1: the origin is attracting. rho = 10: the two nonzero equilibria
    // are attracting for sigma = 10, beta = 8/3. Test both symmetric basins.
    for rho in [0.0, 0.5, 10.0] {
        let model = LorenzParameters(rho: rho)
        for sign in [-1.0, 1.0] {
            var point = SIMD3<Double>(sign, sign, 1)
            let target: SIMD3<Double> = rho < 1 ? .zero : SIMD3(sign * sqrt(model.beta*(rho-1)), sign * sqrt(model.beta*(rho-1)), rho-1)
            for _ in 0..<24000 { point = LorenzMath.rk4(point, parameters: model) }
            #expect(LorenzMath.isSafe(point))
            #expect(error(point, target) < 1e-8)
            #expect(error(LorenzMath.derivative(point, parameters: model), .zero) < 1e-8)
        }
        var reference = LorenzReference()
        try reference.advance(steps: 24000, parameters: model)
        #expect(reference.restarts == 0)
        #expect(error(reference.point, rho < 1 ? .zero : SIMD3(sqrt(model.beta*(rho-1)), sqrt(model.beta*(rho-1)), rho-1)) < 1e-8)
    }
}

@Test func equilibriumIsInvariantAndZAxisMatchesAnalyticDecay() {
    let model = LorenzParameters(rho: 10)
    let x = sqrt(model.beta*(model.rho-1))
    for equilibrium in [SIMD3<Double>.zero, SIMD3(x,x,9), SIMD3(-x,-x,9)] {
        #expect(error(LorenzMath.rk4(equilibrium, parameters: model), equilibrium) < 1e-13)
    }
    // x = y = 0 is invariant for any rho, including chaotic parameter settings.
    var point = SIMD3<Double>(0,0,20)
    for _ in 0..<240 { point = LorenzMath.rk4(point, parameters: model) }
    #expect(point.x == 0 && point.y == 0)
    #expect(abs(point.z - 20*exp(-model.beta)) < 1e-8)
}

@Test func validationRejectsEveryNonFiniteModelComponentAndCountBoundary() {
    for invalid in [Double.nan, .infinity, -.infinity] {
        #expect(!LorenzParameters(sigma: invalid).isValid)
        #expect(!LorenzParameters(rho: invalid).isValid)
        #expect(!LorenzParameters(beta: invalid).isValid)
    }
    for count in [0, 1, 128, 129] {
        for length in [255, 256, 8192, 8193] {
            var value = LorenzConfiguration()
            value.trajectoryCount = count; value.trailLength = length
            #expect(value.isValid == ((1...128).contains(count) && (256...8192).contains(length)))
        }
    }
}

@Test func clockAccountsForDroppedTimeAndPreservesFractionalPhase() {
    var clock = FixedStepClock()
    let dt = LorenzConfiguration.timestep
    #expect(clock.consume(elapsed: dt/2) == 0)
    #expect(clock.consume(elapsed: 1, speed: 4) == 64)
    #expect(abs(clock.remainder - dt/2) < 1e-12)
    #expect(abs(clock.discardedTime - (4 - 64*dt)) < 1e-12)
    #expect(clock.consume(elapsed: 100, paused: true) == 0)
    #expect(clock.consume(elapsed: dt/2) == 1)
    #expect(clock.steps == 65)
}

