@Test func parameterValidationAndStableReference() throws {
    #expect(!LorenzParameters(sigma: .nan).isValid)
    #expect(!LorenzParameters(rho: .infinity).isValid)
    #expect(!LorenzParameters(beta: 0).isValid)
    #expect(!LorenzMath.isSafe(SIMD3(.nan,0,0)))
    #expect(!LorenzMath.isSafe(SIMD3(10000,0,0)))
    var reference = LorenzReference()
    #expect(throws: LorenzError.self) { try reference.advance(steps: 1, parameters: LorenzParameters(sigma: -1)) }
    try reference.advance(steps: 24000, parameters: LorenzParameters())
    #expect(LorenzMath.isSafe(reference.point) && reference.restarts == 0)
    for preset in LorenzPreset.allCases {
        #expect(preset.configuration.isValid)
        #expect(preset.configuration.historyBytes <= 16*1024*1024)
    }
    var invalid = LorenzConfiguration()
    invalid.trajectoryCount = 129
    #expect(!invalid.isValid)
    invalid.trajectoryCount = 1; invalid.trailLength = 8193
    #expect(!invalid.isValid)
}

